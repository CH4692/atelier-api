@dataclass(frozen=True)
class CustomerSpec:
    data: CustomerCreate
    archived: bool


@dataclass(frozen=True)
class InstrumentSpec:
    data: InstrumentCreate
    customer_index: int | None
    archived: bool


@dataclass(frozen=True)
class RepairSpec:
    data: RepairOrderRegister
    instrument_index: int
    customer_index: int
    created_at: datetime
    history: tuple[tuple[RepairStatus, datetime], ...]
    archived: bool
    line: RepairItemCreate


@dataclass(frozen=True)
class SmallPlan:
    as_of: date
    customers: tuple[CustomerSpec, ...]
    instruments: tuple[InstrumentSpec, ...]
    repairs: tuple[RepairSpec, ...]


def build_small(as_of: date) -> SmallPlan:
    """Generate repeatable fictional content relative to an explicit workshop date.

    Database IDs, Argon2 salts, immutable random QR UUIDs and operational audit
    timestamps remain generated by their existing mechanisms.
    """
    if as_of.year < 2000:
        raise ValueError("Demo reference dates must be in or after 2000.")
    customers = []
    for i in range(50):
        first, last = FIRST_NAMES[i % 10], LAST_NAMES[i // 10]
        if i in {10, 20, 30}:
            first, last = (
                ("Musikschule", "Streichensemble", "Jugendorchester")[(i // 10) - 1],
                f"Klanggarten {i}",
            )
        customers.append(
            CustomerSpec(
                CustomerCreate(
                    first_name=first,
                    last_name=last,
                    email=None
                    if i % 7 == 0
                    else f"werkstatt.kunde.{i + 1:02}@example.com",
                    # Bundesnetzagentur Berlin drama-number range, never private contacts.
                    phone=None if i % 5 == 0 else f"+493023125{i:03}",
                ),
                i in {35, 39, 45, 48},
            )
        )
    contexts = (
        "Berufsmusik und Orchester",
        "Musikstudium",
        "Instrumentalunterricht",
        "Familie mit Nachwuchsmusikern",
        "Private Kammermusik",
    )
    instruments = []
    types = (
        [InstrumentType.VIOLIN] * 10
        + [InstrumentType.VIOLA] * 3
        + [InstrumentType.CELLO] * 3
        + [InstrumentType.DOUBLE_BASS]
        + [InstrumentType.BOW] * 3
    )
    for i in range(100):
        kind = types[i % 20]
        owner = i % 40 if i < 70 else None
        length = {
            InstrumentType.VIOLIN: (287, 310, 327, 356)[i % 4],
            InstrumentType.VIOLA: 410,
            InstrumentType.CELLO: 755,
            InstrumentType.DOUBLE_BASS: 1100,
        }.get(kind)
        year = (1890, 1908, 1925, 1956, 1982, 2004, 2016, 2021, 2024, None)[i % 10]
        instruments.append(
            InstrumentSpec(
                InstrumentCreate(
                    type=kind,
                    customer_id=owner + 1 if owner is not None else None,
                    ownership=InstrumentOwnership.CUSTOMER
                    if owner is not None
                    else InstrumentOwnership.WORKSHOP
                    if i < 95
                    else InstrumentOwnership.UNASSIGNED,
                    body_length_mm=float(length) if length is not None else None,
                    bow_weight_g=(58.5 + i % 12)
                    if kind == InstrumentType.BOW
                    else None,
                    maker=(
                        "Werkstatt Fichtenau",
                        "Manufaktur Bogenfeld",
                        "Unbekannte Werkstatt",
                        None,
                    )[i % 4],
                    year_of_manufacture=min(year, as_of.year - 5)
                    if year is not None
                    else None,
                    identification_number=f"{PREFIX}{i + 1:04}",
                    notes=f"Nutzung: {contexts[(owner if owner is not None else i) % len(contexts)]}. Fiktive Werkstatt Klanggarten. {('Schulmodell; Gebrauchsspuren am Griffbrett.', 'Konzertinstrument; regelmäßige Klangkontrolle.', 'Historischer Bestand; behutsame Pflege.', 'Unterricht und Kammermusik; Wirbel kontrollieren.')[i % 4]} "
                    + (
                        "Werkstattbestand für mögliche Schülervermietung; kein Mietvertrag."
                        if 70 <= i < 95
                        else "Demo-Instrument ohne reale Provenienz."
                    ),
                ),
                owner,
                i in {14, 35, 64, 95},
            )
        )
    statuses = (
        [RepairStatus.COMPLETED] * 85
        + [RepairStatus.CANCELLED] * 10
        + [RepairStatus.ACCEPTED] * 15
        + [RepairStatus.AWAITING_APPROVAL] * 10
        + [RepairStatus.IN_PROGRESS] * 12
        + [RepairStatus.AWAITING_MATERIALS] * 8
        + [RepairStatus.READY_FOR_PICKUP] * 10
    )
    anchor = datetime.combine(as_of, time.min, UTC)
    repairs = []
    for i, status in enumerate(statuses):
        instrument_index = i * 11 % 70
        if status not in {RepairStatus.COMPLETED, RepairStatus.CANCELLED}:
            while (
                instruments[instrument_index].archived
                or customers[instruments[instrument_index].customer_index or 0].archived
            ):
                instrument_index = (instrument_index + 1) % 70
        customer_index = instruments[instrument_index].customer_index
        assert customer_index is not None
        kind = instruments[instrument_index].data.type
        scenario = BOW_WORK if kind == InstrumentType.BOW else WORK
        description, price = scenario[i % len(scenario)]
        accepted = anchor - timedelta(
            days=(45 + i * 17 % 1400) if i < 85 else (8 + i % 60)
        )
        duration = 14 if description.startswith("Historische") else 1
        if i >= 85 and duration == 14:
            accepted -= timedelta(days=90)
        path = [RepairStatus.ACCEPTED]
        if status not in {
            RepairStatus.ACCEPTED,
            RepairStatus.CANCELLED,
            RepairStatus.AWAITING_APPROVAL,
        }:
            path.append(RepairStatus.IN_PROGRESS)
        if status == RepairStatus.COMPLETED:
            path.append(RepairStatus.READY_FOR_PICKUP)
        if path[-1] != status:
            path.append(status)
        for previous, target in pairwise(path):
            validate_transition(previous, target)
        history = tuple(
            (stage, accepted + timedelta(days=step * duration))
            for step, stage in enumerate(path)
        )
        performed = history[-1][1] if status == RepairStatus.COMPLETED else None
        due = (
            (accepted + timedelta(days=14)).date()
            if i < 95
            else as_of + timedelta(days=(-10, -3, 0, 1, 3, 7, 14, 35)[i % 8])
        )
        repairs.append(
            RepairSpec(
                RepairOrderRegister(
                    customer_id=customer_index + 1,
                    instrument_id=instrument_index + 1,
                    work_description=f"{description}. Auftrag für {instruments[instrument_index].data.identification_number}.",
                    accepted_at=accepted,
                    expected_completion_date=due,
                    internal_notes=f"Fiktiver Demoauftrag. {STAGE_NOTES[status]} "
                    + (
                        "Wiederkehrender Besuch; Vorarbeiten dokumentiert."
                        if i % 3 == 0
                        else "Termin und Arbeitsumfang mit der Kundschaft abstimmen."
                    ),
                    performed_at=performed,
                ),
                instrument_index,
                customer_index,
                accepted - timedelta(hours=1),
                history,
                i < 85 and i % 17 == 0,
                RepairItemCreate(
                    kind="service",
                    description=description,
                    quantity=Decimal("1.000"),
                    unit_price=Decimal(price),
                ),
            )
        )
    return SmallPlan(as_of, tuple(customers), tuple(instruments), tuple(repairs))
